#!/usr/bin/env node
/**
 * Writes docker/db.env and docker/api.env for `docker compose`.
 *
 *   node docker/scripts/create-env.mjs [--frontend-url http://localhost:8080] [--force]
 *
 * - The database gets a new random password; the API's DATABASE_URL points at
 *   the `db` container with it.
 * - Values that must stay the same as an existing installation (above all the
 *   actor signing key, which a restored database already holds) are copied
 *   from backend/.env when it exists; anything missing is generated.
 * - Existing files are left alone unless --force is given.
 * - No secret is ever printed.
 */
import { randomBytes, randomUUID } from 'node:crypto';
import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..', '..');
const args = process.argv.slice(2);
const force = args.includes('--force');
const urlFlag = args.indexOf('--frontend-url');
const frontendUrl = urlFlag >= 0 ? args[urlFlag + 1] : 'http://localhost:8080';
if (!frontendUrl || !/^https?:\/\/[^/]+$/.test(frontendUrl))
  throw new Error('--frontend-url must be an origin, e.g. http://localhost:8080');

const dbEnvPath = resolve(root, 'docker/db.env');
const apiEnvPath = resolve(root, 'docker/api.env');
if (!force && (existsSync(dbEnvPath) || existsSync(apiEnvPath))) {
  console.log(
    'docker/db.env yoki docker/api.env allaqachon bor — o‘zgartirilmadi (--force bilan qayta yoziladi).',
  );
  process.exit(0);
}

function readEnv(path) {
  if (!existsSync(path)) return {};
  const out = {};
  for (const line of readFileSync(path, 'utf8').split(/\r?\n/)) {
    const match = line.match(/^\s*([A-Z0-9_]+)\s*=\s*(.*)\s*$/);
    if (match) out[match[1]] = match[2].replace(/^(["'])(.*)\1$/, '$2');
  }
  return out;
}

const host = readEnv(resolve(root, 'backend/.env'));
const secret = (bytes = 48) => randomBytes(bytes).toString('base64url');
const dbName = 'fincore';
const dbUser = 'postgres';
const dbPassword = secret(32);
const hostUrl = host.DATABASE_URL ? new URL(host.DATABASE_URL) : null;
const query = hostUrl?.search || '?schema=fincore';

const db = {
  POSTGRES_DB: dbName,
  POSTGRES_USER: dbUser,
  POSTGRES_PASSWORD: dbPassword,
};

const api = {
  DATABASE_URL: `postgresql://${dbUser}:${encodeURIComponent(dbPassword)}@db:5432/${dbName}${query}`,
  FRONTEND_URL: frontendUrl,
  SESSION_SECRET:
    host.SESSION_SECRET && host.SESSION_SECRET.length >= 32 ? host.SESSION_SECRET : secret(),
  SESSION_TTL_HOURS: host.SESSION_TTL_HOURS || '12',
  // Plain http behind nginx on the same origin: lax cookies. Set true (with a
  // https FRONTEND_URL) once a TLS terminator sits in front.
  COOKIE_SECURE: frontendUrl.startsWith('https://') ? 'true' : 'false',
  SWAGGER_ENABLED: 'false',
  RATE_LIMIT_MAX: host.RATE_LIMIT_MAX || '120',
  RATE_LIMIT_TTL_SECONDS: host.RATE_LIMIT_TTL_SECONDS || '60',
  // Must match the key in fincore._actor_signing_keys. A restored database
  // brings the existing one; a fresh one needs scripts/init-actor-key.mjs.
  ACTOR_SIGNING_KEY_ID: host.ACTOR_SIGNING_KEY_ID || randomUUID(),
  ACTOR_SIGNING_KEY: host.ACTOR_SIGNING_KEY || randomBytes(32).toString('base64'),
  ACTOR_TOKEN_TTL_SECONDS: host.ACTOR_TOKEN_TTL_SECONDS || '60',
};
for (const key of [
  'TELEGRAM_ENABLED',
  'TELEGRAM_BOT_TOKEN',
  'TELEGRAM_BOT_USERNAME',
  'TELEGRAM_WEBHOOK_SECRET',
  'TELEGRAM_LINK_TOKEN_PEPPER',
  'TELEGRAM_LINK_TOKEN_TTL_MINUTES',
  'NOTIFICATION_WORKER_ENABLED',
  'NOTIFICATION_WORKER_INTERVAL_MS',
  'NOTIFICATION_WORKER_BATCH_SIZE',
  'NOTIFICATION_WORKER_LEASE_SECONDS',
  'NOTIFICATION_MAX_ATTEMPTS',
  'NOTIFICATION_RETRY_BASE_MS',
  'NOTIFICATION_RETRY_MAX_MS',
])
  if (host[key] !== undefined && host[key] !== '') api[key] = host[key];

const header = (what) =>
  `# ${what} — generated by docker/scripts/create-env.mjs. Secret: never commit or share.\n`;
const body = (values) =>
  Object.entries(values)
    .map(([key, value]) => `${key}=${value}`)
    .join('\n') + '\n';

writeFileSync(dbEnvPath, header('FinCore database container') + body(db), { mode: 0o600 });
writeFileSync(apiEnvPath, header('FinCore API container') + body(api), { mode: 0o600 });
console.log('docker/db.env va docker/api.env yozildi.');
console.log(`  FRONTEND_URL=${frontendUrl}`);
console.log(
  host.ACTOR_SIGNING_KEY
    ? '  Actor imzo kaliti backend/.env dan olindi (tiklanadigan baza bilan mos).'
    : '  Yangi actor imzo kaliti yaratildi — bo‘sh bazada scripts/init-actor-key.mjs bilan o‘rnating.',
);
